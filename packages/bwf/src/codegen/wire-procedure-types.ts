import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { dirname, join, relative } from 'pathslash';
import type { ProcedureFile } from '../procedures/scan.ts';
import { writeFileIfChanged } from './write-if-changed.ts';

type TypeScriptApi = typeof import('typescript/unstable/sync');
type Checker = import('typescript/unstable/sync').Checker;
type Type = import('typescript/unstable/sync').Type;
type TypeReference = import('typescript/unstable/sync').TypeReference;

/** One procedure as its wire types, each printed as TypeScript with no imports. */
export type WireProcedureEntry = {
  name: string;
  input: string;
  output: string;
  errors: string;
};

export type WireProcedureTypes = {
  entries: Array<WireProcedureEntry>;
  /** Types the checker could not resolve. They are written as `unknown`. */
  problems: Array<string>;
};

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const MAX_DEPTH = 16;

/**
 * Generate the types-only file a web workspace includes to type `rpc`: the input, output and
 * error codes of every procedure, written out in full so the file imports nothing from the
 * Worker side.
 */
export function generateWireProcedureTypes(entries: Array<WireProcedureEntry>): string {
  const lines: Array<string> = [];
  lines.push(
    '// Auto-generated by bwf — do not edit',
    'import type { WireProcedure } from "@builtbyfriends/bwf/rpc";',
    '',
    'declare module "@builtbyfriends/bwf/rpc" {',
  );
  if (entries.length === 0) {
    lines.push('  interface ProcedureMap {}');
  } else {
    lines.push('  interface ProcedureMap {');
    for (const entry of entries) {
      lines.push(
        `    ${JSON.stringify(entry.name)}: WireProcedure<${entry.input}, ${entry.output}, ${entry.errors}>;`,
      );
    }
    lines.push('  }');
  }
  lines.push('}', '');
  return lines.join('\n');
}

/**
 * Load TypeScript's programmatic API from the project, falling back to the copy next to bwf.
 * Only TypeScript 7 and later ship it.
 */
async function loadTypeScript(root: string): Promise<TypeScriptApi> {
  const specifier = 'typescript/unstable/sync';
  for (const base of [join(root, 'package.json'), import.meta.url]) {
    try {
      const resolved = createRequire(base).resolve(specifier);
      return (await import(pathToFileURL(resolved).href)) as TypeScriptApi;
    } catch {}
  }
  throw new Error(
    `"procedureTypes" needs TypeScript 7 or later, which provides "${specifier}". Install it with \`bun add -d typescript@^7\`.`,
  );
}

/** Prints a checker type as self-contained TypeScript: named types are written out in full. */
function createPrinter(ts: TypeScriptApi, checker: Checker, problems: Array<string>) {
  const { TypeFlags, SymbolFlags, SignatureKind, ElementFlags } = ts;
  // Decision: Checked in order: `boolean` is a union too, so it has to match first.
  const simple: Array<[number, string]> = [
    [TypeFlags.Any, 'any'],
    [TypeFlags.Unknown, 'unknown'],
    [TypeFlags.Never, 'never'],
    [TypeFlags.Void, 'void'],
    [TypeFlags.Undefined, 'undefined'],
    [TypeFlags.Null, 'null'],
    [TypeFlags.Boolean, 'boolean'],
    [TypeFlags.String, 'string'],
    [TypeFlags.Number, 'number'],
    [TypeFlags.BigInt, 'bigint'],
    [TypeFlags.ESSymbolLike, 'symbol'],
    [TypeFlags.NonPrimitive, 'object'],
  ];
  const globals = new Map<number, boolean>();

  function isGlobalType(type: Type): boolean {
    const symbol = type.getSymbol();
    if (!symbol) {
      return false;
    }
    let known = globals.get(symbol.id);
    if (known === undefined) {
      const found = checker.resolveName(symbol.name, SymbolFlags.Type);
      known = found !== undefined && found.id === symbol.id;
      globals.set(symbol.id, known);
    }
    return known;
  }

  function fallback(type: Type): string {
    return checker.typeToString(type, undefined, 1 | 8_388_608);
  }

  function key(name: string): string {
    return IDENTIFIER.test(name) ? name : JSON.stringify(name);
  }

  function isCallable(type: Type): boolean {
    return checker.getSignaturesOfType(type, SignatureKind.Call).length > 0;
  }

  function joinTypes(
    types: ReadonlyArray<Type>,
    separator: string,
    stack: Set<number>,
    depth: number,
  ) {
    const parts: Array<string> = [];
    for (const member of types) {
      const text = print(member, stack, depth + 1, true);
      if (!parts.includes(text)) {
        parts.push(text);
      }
    }
    if (separator === ' | ') {
      // Decision: Union order follows the checker's type ids, which shift with unrelated edits.
      const rank = (text: string) => (text === 'undefined' ? 2 : text === 'null' ? 1 : 0);
      parts.sort((a, b) => rank(a) - rank(b) || (a < b ? -1 : a > b ? 1 : 0));
    }
    return parts.join(separator);
  }

  function printObject(type: Type, stack: Set<number>, depth: number): string {
    if (isCallable(type)) {
      return 'unknown';
    }
    const members: Array<string> = [];
    for (const property of checker.getPropertiesOfType(type)) {
      const propertyType = checker.getTypeOfSymbol(property);
      if (!propertyType || isCallable(propertyType)) {
        continue;
      }
      const optional = (property.flags & SymbolFlags.Optional) !== 0 ? '?' : '';
      members.push(`${key(property.name)}${optional}: ${print(propertyType, stack, depth + 1)}`);
    }
    for (const info of checker.getIndexInfosOfType(type)) {
      const keyType = print(info.keyType, stack, depth + 1);
      if (keyType === 'string' || keyType === 'number' || keyType === 'symbol') {
        members.push(`[key: ${keyType}]: ${print(info.valueType, stack, depth + 1)}`);
      }
    }
    return members.length === 0 ? '{}' : `{ ${members.join('; ')} }`;
  }

  function printReference(type: Type, stack: Set<number>, depth: number): string | undefined {
    const name = type.getSymbol()?.name;
    if (!name || !isGlobalType(type)) {
      return undefined;
    }
    const args = type.isTypeReference() ? checker.getTypeArguments(type) : [];
    if ((name === 'Array' || name === 'ReadonlyArray') && args.length === 1) {
      const element = print(args[0]!, stack, depth + 1, true);
      return `${name === 'Array' ? '' : 'readonly '}${element}[]`;
    }
    return args.length === 0 ? name : `${name}<${joinTypes(args, ', ', stack, depth)}>`;
  }

  function printTuple(type: TypeReference, stack: Set<number>, depth: number): string {
    const target = type.getTarget();
    const tupleTarget = target.isTupleType() ? target : undefined;
    const flags = tupleTarget?.elementFlags ?? [];
    const elements = checker.getTypeArguments(type).map((element, index) => {
      const text = print(element, stack, depth + 1, true);
      const flag = flags[index] ?? ElementFlags.Required;
      if (flag & ElementFlags.Variadic) {
        return `...${text}`;
      }
      if (flag & ElementFlags.Rest) {
        return `...${text}[]`;
      }
      return flag & ElementFlags.Optional ? `${text}?` : text;
    });
    return `${tupleTarget?.readonly ? 'readonly ' : ''}[${elements.join(', ')}]`;
  }

  function print(type: Type, stack: Set<number>, depth: number, nested = false): string {
    const flags = type.flags;
    if (type.isErrorType()) {
      problems.push(fallback(type));
      return 'unknown';
    }
    for (const [flag, text] of simple) {
      if (flags & flag) {
        return text;
      }
    }
    if (flags & TypeFlags.BooleanLiteral) {
      return String(type.isBooleanLiteralType() && type.value);
    }
    if (flags & (TypeFlags.StringLiteral | TypeFlags.NumberLiteral)) {
      return JSON.stringify((type as { value?: unknown }).value);
    }
    if (flags & (TypeFlags.BigIntLiteral | TypeFlags.TemplateLiteral | TypeFlags.StringMapping)) {
      return fallback(type);
    }

    if (depth > MAX_DEPTH || stack.has(type.id)) {
      return 'unknown';
    }
    stack.add(type.id);
    try {
      if (type.isUnionType()) {
        const text = joinTypes(type.getTypes() ?? [], ' | ', stack, depth);
        return nested ? `(${text})` : text;
      }
      if (type.isIntersectionType()) {
        const text = joinTypes(type.getTypes() ?? [], ' & ', stack, depth);
        return nested ? `(${text})` : text;
      }
      if (type.isObjectType()) {
        if (checker.isTupleType(type) && type.isTypeReference()) {
          return printTuple(type, stack, depth);
        }
        return printReference(type, stack, depth) ?? printObject(type, stack, depth);
      }
      return 'unknown';
    } finally {
      stack.delete(type.id);
    }
  }

  return (type: Type) => print(type, new Set(), 0);
}

/**
 * Resolve the input, output and error types of every procedure with the TypeScript checker, so
 * a workspace that can't see `procedures/` can still type its calls. Needs TypeScript 7.
 */
export async function resolveWireProcedureTypes(options: {
  root: string;
  proceduresDir: string;
  files: Array<ProcedureFile>;
}): Promise<WireProcedureTypes> {
  const { root, proceduresDir, files } = options;
  if (files.length === 0) {
    return { entries: [], problems: [] };
  }
  const ts = await loadTypeScript(root);

  // Decision: A project of its own that reads the app's tsconfig (for paths and module settings) but
  // checks only the procedures, so it doesn't depend on what the app's tsconfig includes.
  const outDir = join(root, '.bwf');
  const base = existsSync(join(root, 'tsconfig.json')) ? '../tsconfig.json' : './tsconfig.json';
  const configPath = join(outDir, 'tsconfig.procedures.json');
  writeFileIfChanged(
    configPath,
    JSON.stringify(
      {
        extends: base,
        compilerOptions: { noEmit: true },
        include: [`${relative(outDir, proceduresDir)}/**/*`],
      },
      null,
      2,
    ) + '\n',
  );

  const api = new ts.API({ cwd: dirname(configPath) });
  try {
    const project = api.updateSnapshot({ openProject: configPath }).getProject(configPath);
    if (!project) {
      throw new Error(`TypeScript could not open ${configPath}.`);
    }
    const { checker, program } = project;
    const problems: Array<string> = [];
    const print = createPrinter(ts, checker, problems);
    const entries: Array<WireProcedureEntry> = [];

    for (const file of files) {
      const sourceFile = program.getSourceFile(join(proceduresDir, file.filePath));
      const moduleSymbol = sourceFile && checker.getSymbolAtLocation(sourceFile);
      if (!moduleSymbol) {
        throw new Error(`TypeScript could not read procedures/${file.filePath}.`);
      }
      for (const exported of checker.getExportsOfModule(moduleSymbol)) {
        const procedure = checker.getTypeOfSymbol(exported);
        if (!procedure || !checker.getPropertyOfType(procedure, '~realtime')) {
          continue;
        }
        const wire = checkerWireTypes(checker, procedure);
        if (!wire) {
          continue;
        }
        const name =
          exported.name === 'default'
            ? file.prefix
            : file.prefix === ''
              ? exported.name
              : `${file.prefix}.${exported.name}`;
        const before = problems.length;
        const entry = {
          name,
          input: print(wire.input),
          output: print(wire.output),
          errors: print(wire.errors),
        };
        for (let index = before; index < problems.length; index++) {
          problems[index] = `${name}: ${problems[index]}`;
        }
        entries.push(entry);
      }
    }
    return { entries, problems };
  } finally {
    api.close();
  }
}

function checkerWireTypes(checker: Checker, procedure: Type) {
  const phantom = checker.getPropertyOfType(procedure, '~types');
  const phantomType = phantom && checker.getTypeOfSymbol(phantom);
  const types = phantomType && checker.getNonNullableType(phantomType);
  if (!types) {
    return undefined;
  }
  const read = (name: string) => {
    const property = checker.getPropertyOfType(types, name);
    return property && checker.getTypeOfSymbol(property);
  };
  const input = read('input');
  const output = read('output');
  const errors = read('errors');
  return input && output && errors ? { input, output, errors } : undefined;
}

/** Write the types-only procedures file named by `procedureTypes`, relative to the project root. */
export async function writeWireProcedureTypes(options: {
  root: string;
  target: string;
  proceduresDir: string;
  files: Array<ProcedureFile>;
}): Promise<{ path: string; changed: boolean; problems: Array<string> }> {
  const { entries, problems } = await resolveWireProcedureTypes(options);
  const path = join(options.root, options.target);
  const changed = writeFileIfChanged(path, generateWireProcedureTypes(entries));
  return { path, changed, problems };
}

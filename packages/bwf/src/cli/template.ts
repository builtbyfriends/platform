type ScaffoldVitePlusDevDependencies = {
  readonly vite: string;
  readonly 'vite-plus': string;
};

/**
 * Vite+ and the Vite+ core it accepts. Both come from the vite-plus release in
 * the repository catalog, so they can't drift apart: vite-plus pins its own
 * core (`npm:@voidzero-dev/vite-plus-core@<version>`) and refuses another one.
 */
export const SCAFFOLD_VITE_PLUS_DEV_DEPENDENCIES: ScaffoldVitePlusDevDependencies = {
  vite: vitePlusManifest.dependencies.vite,
  // Decision: Exact, like the core beside it. A caret let vite-plus 1.8.0 install next to the 1.7.0 core, and it refuses to build.
  'vite-plus': vitePlusManifest.version,
};

export const SCAFFOLD_TOOLCHAIN_OPTIONS = [
  {
    value: 'vite-plus',
    label: 'Vite+',
    hint: 'Uses the Vite+ toolchain and vp commands.',
  },
  {
    value: 'vite',
    label: 'Vite',
    hint: 'Uses plain Vite commands without Vite+.',
  },
] as const;

export const SCAFFOLD_FRAMEWORK_OPTIONS = [
  { value: 'react', label: 'React', hint: 'React single-page app with an optional backend.' },
] as const;

type ScaffoldFrameworkConfig = {
  label: string;
  docsUrl: string;
  /** Dependency whose presence marks a project as using this framework. */
  detectPackage: string;
  dependencies: Record<string, string>;
  devDependencies?: Record<string, string>;
  tsconfigCompilerOptions: Record<string, string>;
};

export const SCAFFOLD_FRAMEWORKS: Record<ScaffoldFramework, ScaffoldFrameworkConfig> = {
  react: {
    label: 'React',
    docsUrl: 'https://react.dev/',
    detectPackage: 'react',
    dependencies: {
      react: '^19.2.4',
      'react-dom': '^19.2.4',
    },
    devDependencies: {
      '@vitejs/plugin-react': '^6.3.0',
      '@types/react': '^19.2.14',
      '@types/react-dom': '^19.2.3',
    },
    tsconfigCompilerOptions: {
      jsx: 'react-jsx',
    },
  },
};

export type SpaStarterTemplate = {
  scripts: Record<string, string>;
  dependencies: Record<string, string>;
  devDependencies: Record<string, string>;
  files: Record<string, string>;
};

export function detectScaffoldFrameworkFromDependencies<T extends Record<string, unknown>>(
  deps: T,
): ScaffoldFramework | undefined {
  for (const { value: framework } of SCAFFOLD_FRAMEWORK_OPTIONS) {
    if (SCAFFOLD_FRAMEWORKS[framework].detectPackage in deps) {
      return framework;
    }
  }
  return undefined;
}

export function getScaffoldTsconfigCompilerOptions(
  framework?: ScaffoldFramework,
): Record<string, string> {
  return framework ? { ...SCAFFOLD_FRAMEWORKS[framework].tsconfigCompilerOptions } : {};
}

export function createSpaStarterTemplate(options: {
  framework: ScaffoldFramework;
  starterMode: ScaffoldStarterMode;
  toolchain?: ScaffoldToolchain;
  bwfPackageSpec: string;
}): SpaStarterTemplate {
  const { framework, starterMode, toolchain = 'vite', bwfPackageSpec } = options;
  const config = SCAFFOLD_FRAMEWORKS[framework];
  const assets = join(getPackageDir(), 'templates', 'assets');
  const files: SpaStarterTemplate['files'] = {
    // Decision: Later init steps add `database` and `worker` to this generated config.
    'bwf.config.ts': renderBwfConfig(
      { routing: { typedRoutes: true } },
      '// Generated by bwf init.',
    ),
    'vite.config.ts': getViteConfig(),
    'index.html': getIndexHtml(),
    'src/main.tsx': getMain(),
    'src/App.tsx': getApp(framework, starterMode),
    'src/style.css': starterStyles,
    'src/vite-env.d.ts': '/// <reference types="vite/client" />\n',
    'public/stack.svg': readFileSync(join(assets, 'stack.svg'), 'utf8'),
    'public/bwf.svg': readFileSync(join(assets, 'bwf.svg'), 'utf8'),
    [`public/${framework}.svg`]: readFileSync(join(assets, `${framework}.svg`), 'utf8'),
    'public/icons.svg': readFileSync(join(assets, 'icons.svg'), 'utf8'),
  };

  if (starterMode !== 'spa') {
    files['routes/api/messages.ts'] = getMessagesRoute();
    files['routes/api/hello.ts'] = getHelloRoute(config.label, starterMode);
    files['db/schema.ts'] = getSchemaFile(starterMode);
    files['db/seed.ts'] = getSeedFile();
  }

  const dependencies: SpaStarterTemplate['dependencies'] = {
    ...SCAFFOLD_BASE_DEPENDENCIES,
    ...config.dependencies,
  };
  if (starterMode !== 'spa') {
    dependencies.zod = '^4.6.7';
  }
  const devDependencies: SpaStarterTemplate['devDependencies'] = {
    '@builtbyfriends/bwf': bwfPackageSpec,
    ...SCAFFOLD_BASE_DEV_DEPENDENCIES,
  };
  if (toolchain === 'vite-plus') {
    Object.assign(devDependencies, SCAFFOLD_VITE_PLUS_DEV_DEPENDENCIES);
  }
  Object.assign(devDependencies, config.devDependencies);

  return {
    scripts: {
      dev: toolchain === 'vite-plus' ? 'vp dev' : 'vite',
      build: toolchain === 'vite-plus' ? 'vp build' : 'vite build',
      preview: toolchain === 'vite-plus' ? 'vp preview' : 'vite preview',
      // Decision: `.bwf/` is gitignored, so fresh clones and new scaffolds need the
      // generated types before the editor opens tsconfig.json.
      postinstall: 'bwf prepare',
    },
    dependencies,
    devDependencies,
    files,
  };
}

function getViteConfig(): string {
  return `import react from "@vitejs/plugin-react";
import { defineConfig } from "vite";
import { bwfPlugin } from "@builtbyfriends/bwf";

export default defineConfig({
  plugins: [react(), bwfPlugin()],
});
`;
}


function getMessagesDemo(): string {
  return `<section class="starter-demo" aria-labelledby="messages-title">
  <div class="demo-content">
    <h2 id="messages-title">Messages</h2>
    {messages.length === 0 ? (
      <p class="empty-state">
        No messages yet. Run <code>bwf db seed</code> to load the sample row from <code>db/seed.ts</code>.
      </p>
    ) : (
      <ul class="messages">
        {messages.map((message) => (
          <li key={message.id}>
            <strong>{message.text}</strong>
            <small>{String(message.createdAt)}</small>
          </li>
        ))}
      </ul>
    )}
    <form onSubmit={addMessage} class="message-form">
      <label htmlFor="message-text">Message</label>
      <div class="message-fields">
        <input id="message-text" name="text" value={text} onChange={(event) => setText(event.target.value)} required maxLength={1000} />
        <button type="submit" disabled={pending}>Add message</button>
      </div>
    </form>
  </div>
</section>`;
}

function indent(source: string, spaces: number): string {
  return source
    .split('\n')
    .map((line) => ' '.repeat(spaces) + line)
    .join('\n');
}
